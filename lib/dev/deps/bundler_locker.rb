# typed: strict
# frozen_string_literal: true

require "pathname"
require_relative "locker"
require_relative "scoped_declaration"
require_relative "shadowenv_exec"

module Dev
  module Deps
    # Whole-set gem solve through bundler.
    #
    # Generates a Gemfile from the declared :bundler deps (dependencies.rb is
    # the source of truth) and runs `bundle lock` to pin the full gem graph
    # into Gemfile.lock. BundlerRepository reads the pins back from there.
    #
    # `bundle lock` is conservative on its own: a Gemfile.lock on disk keeps
    # every gem that still satisfies the Gemfile. The UnlockSet maps onto
    # bundler's own unlock: the named gems become `--update <gem>…`, the
    # full re-lock `--update` alone.
    class BundlerLocker < Locker
      extend T::Sig

      # `bundle lock` exited non-zero — typically an unresolvable gem set.
      class LockError < StandardError; end

      GEMFILE = "Gemfile"
      RUBYGEMS_SOURCE = "https://rubygems.org"
      UPDATE_FLAG = "--update"

      GENERATED_HEADER = <<~HEADER
        # Generated by dev from dependencies.rb. Do not edit.
        # Add or change gems in dependencies.rb and run `dev deps update`.
      HEADER

      # @param project_root [Pathname, String] root the Gemfile/Gemfile.lock live in
      # @param ruby_version [String, nil] the exact Ruby the lock pins, for
      #   the Gemfile's `ruby` directive — the locked version, not the
      #   manifest's range, so bundler's solve and the pin agree — or nil
      #   to omit it (a project declaring no Ruby)
      # @param shadowenv_exec [ShadowenvExec] spawn seam for the project's Ruby
      #   toolchain — `bundle lock` must solve under the pinned Ruby and its
      #   bundler, not whatever the invoking shell carries (dev#76)
      sig do
        params(
          project_root: T.any(Pathname, String),
          ruby_version: T.nilable(String),
          shadowenv_exec: ShadowenvExec,
        ).void
      end
      def initialize(project_root:, ruby_version: nil, shadowenv_exec: ShadowenvExec.new(project_root: Pathname(project_root)))
        super()
        @project_root = T.let(Pathname(project_root), Pathname)
        @ruby_version = ruby_version
        @shadowenv_exec = shadowenv_exec
      end

      # Generate the Gemfile from all gem declarations and lock it.
      #
      # @param declarations [Array<ScopedDeclaration>] :bundler declarations
      # @param unlock [UnlockSet] which gems float; a name that is not one
      #   of these declarations floats nothing here
      # @return [void]
      # @raise [LockError] if bundle lock fails
      sig { override.params(declarations: T::Array[ScopedDeclaration], unlock: UnlockSet).void }
      def lock(declarations, unlock: UnlockSet.none)
        return if declarations.empty?

        write_gemfile(declarations)
        run_bundle_lock(update_args(declarations, unlock))
      end

      private

      # Generate a Gemfile from the declarations, mapping each dev group to a
      # bundler group (the default group stays unscoped, like a hand-written
      # Gemfile's top section).
      #
      # @param declarations [Array<ScopedDeclaration>]
      # @return [void]
      sig { params(declarations: T::Array[ScopedDeclaration]).void }
      def write_gemfile(declarations)
        lines = [GENERATED_HEADER, %(source "#{RUBYGEMS_SOURCE}")]
        lines << %(ruby "#{@ruby_version}") if @ruby_version

        ungrouped, grouped = declarations.partition { |decl| decl.scope.group == DSL::DEFAULT_GROUP }

        ungrouped.each { |decl| lines << gem_line(decl) }
        grouped.group_by { |decl| decl.scope.group }.each do |group, group_decls|
          lines << ""
          lines << "group :#{group} do"
          group_decls.each { |decl| lines << "  #{gem_line(decl)}" }
          lines << "end"
        end

        gemfile_path.write("#{lines.join("\n")}\n")
      end

      # Render a single `gem` line from a declaration's constraint. "version" is
      # the positional requirement; any other constraint keys become gem options.
      #
      # @param decl [ScopedDeclaration]
      # @return [String]
      sig { params(decl: ScopedDeclaration).returns(String) }
      def gem_line(decl)
        parts = [%(gem "#{decl.name}")]
        constraint = decl.constraint
        parts << constraint["version"].inspect if constraint["version"]

        options = constraint.reject { |key, _| key == "version" }
        options.each { |key, value| parts << "#{key}: #{value.inspect}" }

        parts.join(", ")
      end

      # bundler's unlock for the UnlockSet: `--update` alone floats every
      # gem, `--update <gem>…` floats the named ones among these
      # declarations (bundler refuses a name the Gemfile lacks, so names
      # from other channels never reach it), nothing when none is named.
      #
      # @param declarations [Array<ScopedDeclaration>] the :bundler declarations
      # @param unlock [UnlockSet]
      # @return [Array<String>] argv appended to `bundle lock`
      sig { params(declarations: T::Array[ScopedDeclaration], unlock: UnlockSet).returns(T::Array[String]) }
      def update_args(declarations, unlock)
        return [UPDATE_FLAG] if unlock.all?

        gems = declarations.map(&:name).uniq.select { |name| unlock.floats?(name) }
        gems.empty? ? [] : [UPDATE_FLAG, *gems]
      end

      # Run `bundle lock` against the generated Gemfile to write Gemfile.lock,
      # through the ShadowenvExec seam for the same reason BundlerIntegration
      # does: the resolve must happen under the project's provisioned Ruby, and
      # the Gemfile.lock's BUNDLED WITH must record that Ruby's bundler.
      #
      # @param update_args [Array<String>] bundler's unlock argv (#update_args)
      # @raise [LockError] if bundle lock fails
      # @return [void]
      sig { params(update_args: T::Array[String]).void }
      def run_bundle_lock(update_args)
        # T.unsafe: Sorbet accepts a splat only of statically sized arrays.
        _out, err, status = T.unsafe(@shadowenv_exec).capture3(
          "bundle", "lock", *update_args,
          env: { "BUNDLE_GEMFILE" => gemfile_path.to_s },
        )
        raise LockError, "bundle lock failed: #{err}" unless status.success?
      end

      # @return [Pathname]
      sig { returns(Pathname) }
      def gemfile_path
        @project_root / GEMFILE
      end
    end
  end
end
