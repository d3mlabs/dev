# typed: strict
# frozen_string_literal: true

require "sorbet-runtime"
require "yaml"
require "fileutils"
require "pathname"
require_relative "dependency"

module Dev
  module Deps
    # Pure serialization: locks/reads Dependencies to/from the YAML lockfile.
    # No resolution logic — that's the Resolver's job.
    #
    # One lockfile, deps.lock, every group in it (ADR-0011). Entries nest by
    # integration, mirroring package identity (integration + name), so the
    # same name under two integrations occupies two keys; a pin's install
    # scoping (host, env) is an attribute beside its version:
    #
    #   brew:
    #     zlib: { group: app, version: "1.3" }
    #     powershell: { group: build, version: "7.4.0", env: ci }
    #   cmake:
    #     zlib: { group: app, version: "1.3.1" }
    #
    # The reader also accepts the legacy flat format (name-keyed, integration
    # recorded in the value hash) so repos keep installing from lockfiles
    # written before the nesting; that shim is deleted once every consumer
    # repo's lockfiles have been rewritten by dev deps update (issue #146).
    class Lockfile
      extend T::Sig

      # The checkout still carries build-deps.lock, which dev no longer reads:
      # its pins would be silently missing from the install. dev deps update
      # folds them into deps.lock and removes the file.
      class RetiredBuildLockError < StandardError; end

      HEADER = <<~COMMENT
        # Generated by dev. Do not edit.
        # Edit dependencies.rb and run dev deps update to change.
      COMMENT

      # Header line recording the SHA-256 of the dependencies.rb the lockfile
      # was generated from. The staleness check (Dev::Deps::Staleness) compares
      # it against the current manifest to detect "declarations changed but
      # dev deps update wasn't run". A comment so the YAML payload stays pure deps.
      MANIFEST_DIGEST_PREFIX = "# dependencies-digest: "

      DEPS_LOCK_FILE = "deps.lock"

      # The build group's former lockfile, retired by ADR-0011. Named only to
      # remove it on re-lock and to refuse an install that would skip it.
      RETIRED_BUILD_LOCK_FILE = "build-deps.lock"

      # @param dir [Pathname] directory containing the lockfile
      sig { params(dir: T.any(Pathname, String)).void }
      def initialize(dir:)
        @dir = T.let(Pathname(dir), Pathname)
        @manifest_digest = T.let(nil, T.nilable(String))
      end

      # Lock all dependencies into deps.lock. A retired build-deps.lock beside
      # it is removed: this write is the re-lock that folds it in.
      #
      # @param deps [Array<Dependency>]
      # @param manifest_digest [String, nil] SHA-256 hex of the dependencies.rb
      #   these locks were resolved from, recorded in the lockfile's header
      # @return [void]
      sig { params(deps: T::Array[Dependency], manifest_digest: T.nilable(String)).void }
      def lock(deps, manifest_digest: nil)
        @manifest_digest = manifest_digest

        write_lockfile(deps, @dir / DEPS_LOCK_FILE) if deps.any?
        FileUtils.rm_f(@dir / RETIRED_BUILD_LOCK_FILE)
      end

      # The manifest digest recorded when the lockfile was generated, or nil
      # for a lockfile predating the staleness check (treated as unknown, not
      # stale — legacy locks shouldn't nag until their next dev deps update).
      #
      # @return [String, nil] SHA-256 hex
      sig { returns(T.nilable(String)) }
      def manifest_digest
        path = @dir / DEPS_LOCK_FILE
        return nil unless path.exist?

        path.each_line do |line|
          return line.delete_prefix(MANIFEST_DIGEST_PREFIX).strip if line.start_with?(MANIFEST_DIGEST_PREFIX)
          break unless line.start_with?("#") || line.strip.empty?
        end
        nil
      end

      # Read all locked dependencies.
      #
      # @return [Array<Dependency>]
      # @raise [RetiredBuildLockError] if build-deps.lock is still present
      sig { returns(T::Array[Dependency]) }
      def read
        if (@dir / RETIRED_BUILD_LOCK_FILE).exist?
          raise RetiredBuildLockError,
            "#{@dir / RETIRED_BUILD_LOCK_FILE} is retired (ADR-0011): dev reads one lockfile, #{DEPS_LOCK_FILE}. " \
              "Run dev deps update to fold it in and remove it."
        end

        read_lockfile(@dir / DEPS_LOCK_FILE)
      end

      private

      # Write deps to a lockfile at path, with the comment header.
      #
      # @param deps [Array<Dependency>]
      # @param path [Pathname]
      # @return [void]
      sig { params(deps: T::Array[Dependency], path: Pathname).void }
      def write_lockfile(deps, path)
        FileUtils.mkdir_p(path.dirname)
        yaml_hash = deps_to_yaml_hash(deps)
        File.write(path, header + YAML.dump(yaml_hash).delete_prefix("---\n"))
      end

      # The comment header, including the manifest digest when one was given.
      #
      # @return [String]
      sig { returns(String) }
      def header
        lines = HEADER.dup
        lines << "#{MANIFEST_DIGEST_PREFIX}#{@manifest_digest}\n" if @manifest_digest
        lines << "\n"
        lines
      end

      # @param path [Pathname]
      # @return [Array<Dependency>]
      sig { params(path: Pathname).returns(T::Array[Dependency]) }
      def read_lockfile(path)
        return [] unless path.exist?

        yaml = YAML.safe_load(File.read(path), permitted_classes: [Symbol])
        return [] if yaml.nil?

        yaml_hash_to_deps(yaml)
      end

      # Serialize deps as integration → name → attrs, one section per
      # integration, so identity (integration + name) survives the trip to
      # disk without a composite key.
      #
      # @param deps [Array<Dependency>]
      # @return [Hash]
      sig { params(deps: T::Array[Dependency]).returns(T::Hash[String, T.untyped]) }
      def deps_to_yaml_hash(deps)
        result = T.let({}, T::Hash[String, T.untyped])
        deps.each do |dep|
          section = result[dep.integration.to_s] ||= {}
          section[dep.name] = dep_to_hash(dep)
        end
        result
      end

      # A dep's value hash: group, version/hash when present, then metadata.
      # The integration is not repeated here — it's the section key.
      #
      # @param dep [Dependency]
      # @return [Hash]
      sig { params(dep: Dependency).returns(T::Hash[String, T.untyped]) }
      def dep_to_hash(dep)
        h = T.let({ "group" => dep.group.to_s }, T::Hash[String, T.untyped])
        h["version"] = dep.version if dep.version
        h["hash"] = dep.hash if dep.hash
        dep.metadata&.each { |k, v| h[k.to_s] = v } unless dep.metadata.nil? || dep.metadata.empty?
        h
      end

      # @param yaml [Hash] a parsed lockfile
      # @return [Array<Dependency>]
      sig { params(yaml: T::Hash[String, T.untyped]).returns(T::Array[Dependency]) }
      def yaml_hash_to_deps(yaml)
        deps = T.let([], T::Array[Dependency])

        yaml.each do |key, value|
          next unless value.is_a?(Hash)

          deps.concat(entry_to_deps(key, value))
        end

        deps
      end

      # One lockfile entry, current or legacy format. An integration section
      # maps names to attrs; a legacy entry is name-keyed and records its
      # integration in the value hash — the discriminator, since the writer
      # always recorded it there and never records it in sections.
      #
      # @param key [String] integration name, or a dep name (legacy)
      # @param value [Hash] name → attrs section, or a dep's attrs (legacy)
      # @return [Array<Dependency>]
      sig { params(key: String, value: T::Hash[String, T.untyped]).returns(T::Array[Dependency]) }
      def entry_to_deps(key, value)
        return [hash_to_dep(key, value)] if value.key?("integration")

        value.map { |name, attrs| hash_to_dep(name, attrs, integration: key.to_sym) }
      end

      # @param name [String] the dep's name
      # @param attrs [Hash] the dep's value hash
      # @param integration [Symbol, nil] from the section key; nil for legacy
      #   entries, which carry it in attrs
      # @return [Dependency]
      sig do
        params(
          name: String,
          attrs: T::Hash[String, T.untyped],
          integration: T.nilable(Symbol),
        ).returns(Dependency)
      end
      def hash_to_dep(name, attrs, integration: nil)
        metadata = attrs.reject { |k, _| %w[integration group version hash].include?(k) }

        Dependency.new(
          name: name,
          integration: integration || attrs["integration"].to_sym,
          group: attrs["group"].to_sym,
          version: attrs["version"],
          hash: attrs["hash"],
          metadata: metadata.empty? ? {} : metadata,
        )
      end
    end
  end
end
